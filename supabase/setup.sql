create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
create table if not exists public.profile (
  id int primary key default 1 check (id = 1),
  name text not null default 'Ankit Kumar',
  role text default 'Student · Developer · Curious Learner',
  intro text default 'I enjoy turning ideas into useful digital experiences and learning new technologies.',
  about text default 'I believe in learning by building and improving a little every day.',
  email text default '',
  location text default 'India',
  photo_url text default '',
  social_links jsonb not null default '[]'::jsonb,
  updated_at timestamptz not null default now()
);
create table if not exists public.skills (
  id bigint generated by default as identity primary key,
  name text not null,
  category text default '',
  created_at timestamptz not null default now()
);
create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  tags text[] not null default '{}',
  link text default '',
  image_url text default '',
  featured boolean not null default false,
  created_at timestamptz not null default now()
);
create table if not exists public.experiences (
  id bigint generated by default as identity primary key,
  role text not null,
  organization text default '',
  period text default '',
  description text default '',
  sort_order int not null default 0,
  created_at timestamptz not null default now()
);
create table if not exists public.education (
  id bigint generated by default as identity primary key,
  course text not null,
  institution text default '',
  period text default '',
  details text default '',
  sort_order int not null default 0,
  created_at timestamptz not null default now()
);

