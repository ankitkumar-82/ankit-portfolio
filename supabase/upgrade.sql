-- ANKIT KUMAR PORTFOLIO: SAFE ADDITIVE UPGRADE
-- Run this AFTER the original setup.sql. It does not drop or overwrite existing portfolio data.

create table if not exists public.site_settings (
  id int primary key default 1 check (id=1),
  theme text not null default 'midnight',
  layout text not null default 'showcase',
  font text not null default 'space',
  accent_color text not null default '#a78bfa',
  intro_enabled boolean not null default true,
  intro_title text not null default 'Hello, I am Ankit Kumar',
  intro_subtitle text not null default 'Student · Developer · Curious Learner',
  intro_repeat text not null default 'session',
  photo_shape text not null default 'rounded',
  photo_size int not null default 330,
  photo_border_color text not null default '#a78bfa',
  photo_glow boolean not null default false,
  updated_at timestamptz not null default now()
);
insert into public.site_settings(id) values(1) on conflict(id) do nothing;

create table if not exists public.achievements (
  id bigint generated by default as identity primary key,
  title text not null,
  kind text not null default 'Achievement',
  description text not null default '',
  link text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 80),
  email text not null check (char_length(email) between 3 and 160),
  subject text not null check (char_length(subject) between 1 and 120),
  message text not null check (char_length(message) between 1 and 3000),
  created_at timestamptz not null default now()
);

alter table public.site_settings enable row level security;
alter table public.achievements enable row level security;
alter table public.contact_messages enable row level security;

drop policy if exists "public reads site settings" on public.site_settings;
create policy "public reads site settings" on public.site_settings for select to anon,authenticated using(true);
drop policy if exists "admin manages site settings" on public.site_settings;
create policy "admin manages site settings" on public.site_settings for all to authenticated using(public.is_portfolio_admin()) with check(public.is_portfolio_admin());
drop policy if exists "public reads achievements" on public.achievements;
create policy "public reads achievements" on public.achievements for select to anon,authenticated using(true);
drop policy if exists "admin manages achievements" on public.achievements;
create policy "admin manages achievements" on public.achievements for all to authenticated using(public.is_portfolio_admin()) with check(public.is_portfolio_admin());
drop policy if exists "visitors can send messages" on public.contact_messages;
create policy "visitors can send messages" on public.contact_messages for insert to anon,authenticated with check(true);
drop policy if exists "admin reads messages" on public.contact_messages;
create policy "admin reads messages" on public.contact_messages for select to authenticated using(public.is_portfolio_admin());
drop policy if exists "admin deletes messages" on public.contact_messages;
create policy "admin deletes messages" on public.contact_messages for delete to authenticated using(public.is_portfolio_admin());

grant select on public.site_settings,public.achievements to anon,authenticated;
grant insert,update,delete on public.site_settings,public.achievements to authenticated;
grant insert on public.contact_messages to anon,authenticated;
grant select,delete on public.contact_messages to authenticated;
grant usage,select on all sequences in schema public to authenticated,anon;

-- Secure admin check used by the updated dashboard. Returns true only for the signed-in allow-listed user.
create or replace function public.is_portfolio_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.admins where user_id=(select auth.uid()));
$$;
revoke all on function public.is_portfolio_admin() from public;
grant execute on function public.is_portfolio_admin() to anon,authenticated;
