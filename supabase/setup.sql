create or replace function public.is_portfolio_admin()
returns boolean language sql stable security definer
set search_path = '' as $$
  select exists (
    select 1 from public.admins
    where user_id = (select auth.uid())
  );
$$;
revoke all on function public.is_portfolio_admin() from public;
grant execute on function public.is_portfolio_admin() to anon, authenticated;

alter table public.admins enable row level security;
alter table public.profile enable row level security;
alter table public.skills enable row level security;
alter table public.projects enable row level security;
alter table public.experiences enable row level security;
alter table public.education enable row level security;

create policy "admin can read admin identity" on public.admins
for select to authenticated using (user_id = (select auth.uid()) and public.is_portfolio_admin());

create policy "public reads profile" on public.profile
for select to anon, authenticated using (true);
create policy "admin updates profile" on public.profile
for all to authenticated using (public.is_portfolio_admin()) with check (public.is_portfolio_admin());

create policy "public reads skills" on public.skills
for select to anon, authenticated using (true);
create policy "admin manages skills" on public.skills
for all to authenticated using (public.is_portfolio_admin()) with check (public.is_portfolio_admin());

create policy "public reads projects" on public.projects
for select to anon, authenticated using (true);
create policy "admin manages projects" on public.projects
for all to authenticated using (public.is_portfolio_admin()) with check (public.is_portfolio_admin());

create policy "public reads experiences" on public.experiences
for select to anon, authenticated using (true);
create policy "admin manages experiences" on public.experiences
for all to authenticated using (public.is_portfolio_admin()) with check (public.is_portfolio_admin());

create policy "public reads education" on public.education
for select to anon, authenticated using (true);
create policy "admin manages education" on public.education
for all to authenticated using (public.is_portfolio_admin()) with check (public.is_portfolio_admin());

grant select on public.profile, public.skills, public.projects, public.experiences, public.education to anon, authenticated;
grant insert, update, delete on public.profile, public.skills, public.projects, public.experiences, public.education to authenticated;
grant usage, select on all sequences in schema public to authenticated;

